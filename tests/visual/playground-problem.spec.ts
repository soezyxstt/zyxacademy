import { expect, test } from '@playwright/test';
import { mockTerminal } from './terminal-fixture';

test('problem composer and Zyra response', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
  page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
  await mockTerminal(page);
  await page.route('**/api/zyra/attachments', route => route.fulfill({ json: { id: 'image-id', sessionId: 'test-session', width: 1, height: 1 } }));
  let release!: () => void;
  const pending = new Promise<void>(resolve => { release = resolve; });
  let request: { attachmentIds: string[] };
  await page.route('**/api/zyra/chat', async route => { request = route.request().postDataJSON(); await pending; await route.fulfill({ contentType: 'text/event-stream', body: `data: ${JSON.stringify({ type: 'text-delta', textDelta: 'Berikut kode untuk menghitung luas.\n\n```python\n# Hitung luas\nprint(6 * 4)\n```' })}\n\ndata: [DONE]\n\n` }); });
  const response = await page.goto('/visual-fixtures/coding?terminal=1');
  expect(response?.status()).toBeLessThan(400);
  expect(new URL(page.url()).pathname).toBe('/visual-fixtures/coding');
  await expect(page.getByRole('textbox', { name: 'Kode Python' })).toBeVisible();
  await page.getByRole('button', { name: 'Masalah yang ingin diselesaikan' }).click();
  await expect(page.getByRole('textbox', { name: 'Deskripsi masalah' })).toBeVisible();
  await page.screenshot({ path: info.outputPath('screenshots/problem-open.png'), fullPage: true });
  await page.getByRole('textbox', { name: 'Deskripsi masalah' }).fill('Hitung luas persegi panjang dengan panjang 6 dan lebar 4.');
  await page.locator('input[type=file]').setInputFiles({ name: 'soal.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64') });
  await expect(page.getByLabel('Lampiran gambar')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Buat kode' })).toBeEnabled();
  await page.screenshot({ path: info.outputPath('screenshots/problem-filled.png'), fullPage: true });
  await page.getByRole('button', { name: 'Buat kode' }).click();
  await expect(page.getByText('Zyra sedang membuat kode...')).toBeVisible();
  await page.screenshot({ path: info.outputPath('screenshots/problem-loading.png'), fullPage: true });
  release();
  await expect(page.getByRole('button', { name: 'Gunakan kode di editor' })).toBeVisible();
  expect(request.attachmentIds).toEqual(['image-id']);
  await page.screenshot({ path: info.outputPath('screenshots/problem-answer.png'), fullPage: true });
  await page.getByRole('button', { name: 'Gunakan kode di editor' }).click();
  await expect(page.getByRole('textbox', { name: 'Kode Python' })).toContainText('print(6 * 4)');
  await page.getByRole('button', { name: 'Masalah yang ingin diselesaikan' }).click();
  await expect(page.getByRole('textbox', { name: 'Deskripsi masalah' })).toBeHidden();
  await page.getByRole('button', { name: 'Masalah yang ingin diselesaikan' }).click();
  await expect(page.getByLabel('Lampiran gambar')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  expect(errors).toEqual([]);
});
