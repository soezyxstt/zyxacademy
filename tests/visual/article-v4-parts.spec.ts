import { expect, test } from "@playwright/test";

test("V4 parts preserve prose, formula, meaning, and visual order", async ({ page }, testInfo) => {
  test.setTimeout(90_000);
  const failures: string[] = [];
  page.on("pageerror", (error) => failures.push(error.message));
  page.on("console", (message) => { if (message.type() === "error") failures.push(message.text()); });
  page.on("response", (response) => { if (response.status() >= 400) failures.push(`${response.status()} ${response.url()}`); });
  await page.route("**/api/student/articles/ordered-parts-article/progress", (route) => route.fulfill({ json: { maxReadPercent: 0, completed: false, timeSpentSeconds: 0 } }));
  await page.emulateMedia({ reducedMotion: "reduce" });
  const response = await page.goto("/visual-fixtures/structured-article?orderedParts=1", { timeout: 90_000 });
  expect(response?.status()).toBeLessThan(400);
  expect(new URL(page.url()).pathname).toBe("/visual-fixtures/structured-article");
  expect(new URL(page.url()).searchParams.get("orderedParts")).toBe("1");
  const parts = page.locator("[data-article-parts]");
  await expect(parts).toHaveCount(1);
  expect(await parts.locator(":scope > [data-part-id]").evaluateAll((elements) => elements.map((element) => element.getAttribute("data-part-id")))).toEqual(["opening", "condition", "bridge", "bound-visual", "closing"]);
  await expect(page.getByText("Isi kompatibilitas tidak boleh dirender dua kali.")).toHaveCount(0);
  await parts.locator('[data-part-kind="visual_ref"]').scrollIntoViewIfNeeded();
  await expect(page.getByRole("figure", { name: "Geser dan skala grafik", exact: true })).toHaveCount(1);
  await expect(parts.locator('svg[role="img"]')).toBeVisible();
  expect(await parts.locator('[data-part-kind="math_unit"] .katex').count()).toBeGreaterThan(0);
  await page.evaluate(async () => document.fonts.ready);
  await page.addStyleTag({ content: "nextjs-portal { display: none !important; }" });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("screenshots/v4-ordered-parts.png"), fullPage: true, animations: "disabled" });
  await parts.getByRole("button", { name: "Parameter", exact: true }).click();
  const slider = parts.getByRole("slider", { name: "Ubah nilai Vertikal", exact: true });
  await slider.fill("2");
  await expect(slider).toHaveValue("2");
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("screenshots/v4-ordered-parts-interaction.png"), fullPage: true, animations: "disabled" });
  await parts.getByRole("button", { name: "Interaksi grafik", exact: true }).click();
  const plot = parts.locator('svg[role="img"]');
  await plot.focus();
  for (let i = 0; i < 5; i++) await plot.press("ArrowRight");
  expect(await plot.locator("path[data-series-id]").evaluateAll(paths => paths.some(path => Boolean(path.getAttribute("d"))))).toBe(true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("screenshots/v4-domain-partial.png"), fullPage: true, animations: "disabled" });
  for (let i = 0; i < 6; i++) await plot.press("ArrowRight");
  expect(await plot.locator("path[data-series-id]").evaluateAll(paths => paths.every(path => !path.getAttribute("d")))).toBe(true);
  await expect(parts.getByText("Rumus belum dapat ditampilkan")).toHaveCount(0);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("screenshots/v4-domain-empty.png"), fullPage: true, animations: "disabled" });
  const width = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, client: document.documentElement.clientWidth }));
  expect(width.scroll).toBeLessThanOrEqual(width.client);
  expect(failures).toEqual([]);
});
