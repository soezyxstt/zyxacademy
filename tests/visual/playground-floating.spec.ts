import { expect, test } from "@playwright/test";
import { mockTerminal } from "./terminal-fixture";

test("floating composer preserves its state and safely places generated code", async ({ page }, info) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  page.on("response", response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
  await mockTerminal(page);
  let uploads = 0;
  await page.route("**/api/zyra/attachments", route => { uploads++; return route.fulfill({ json: { id: "image-id", sessionId: "test-session", width: 1, height: 1 } }); });
  let release!: () => void;
  const pending = new Promise<void>(resolve => { release = resolve; });
  await page.route("**/api/zyra/chat", async route => {
    await pending;
    await route.fulfill({ contentType: "text/event-stream", body: `data: ${JSON.stringify({ type: "text-delta", textDelta: "Berikut hasilnya.\n\n```python\nprint(24)\n```" })}\n\ndata: [DONE]\n\n` });
  });
  const response = await page.goto("/visual-fixtures/coding?terminal=1");
  expect(response?.status()).toBe(200);
  expect(new URL(page.url()).pathname).toBe("/visual-fixtures/coding");
  const toggle = page.getByRole("button", { name: "Masalah yang ingin diselesaikan" });
  const editor = page.getByRole("textbox", { name: "Kode Python" });
  const prompt = page.getByRole("textbox", { name: "Deskripsi masalah" });
  await toggle.click();
  await expect(page.getByRole("textbox", { name: "Pertanyaan", exact: true })).toBeHidden();
  const panel = page.locator("[id]").filter({ has: prompt }).last();
  expect((await panel.boundingBox())!.height).toBeLessThan(250);
  await prompt.fill("Hitung luas persegi panjang.");
  await prompt.evaluate(element => {
    const clipboard = new DataTransfer();
    const bytes = Uint8Array.from(atob("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII="), char => char.charCodeAt(0));
    clipboard.items.add(new File([bytes], "soal.png", { type: "image/png", lastModified: 5 }));
    for (let i = 0; i < 2; i++) element.dispatchEvent(new ClipboardEvent("paste", { clipboardData: clipboard, bubbles: true, cancelable: true }));
  });
  await expect(page.getByLabel("Lampiran gambar")).toBeVisible();
  await expect.poll(() => uploads).toBe(1);
  await page.screenshot({ path: info.outputPath("screenshots/floating-open.png") });
  await editor.fill("");
  await page.getByRole("button", { name: "Buat kode" }).click();
  await expect(page.getByText("Zyra sedang membuat kode...")).toBeVisible();
  await page.screenshot({ path: info.outputPath("screenshots/floating-generating.png") });
  await toggle.click();
  await expect(prompt).toBeHidden();
  await page.screenshot({ path: info.outputPath("screenshots/floating-collapsed.png") });
  release();
  await expect(editor).toContainText("print(24)");
  await toggle.click();
  await expect(prompt).toHaveValue("Hitung luas persegi panjang.");
  await expect(page.getByLabel("Lampiran gambar")).toBeVisible();
  await expect(page.getByText("Berikut hasilnya.")).toBeVisible();
  await expect(panel.locator("pre")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Buat kode" })).toBeInViewport();
  await page.screenshot({ path: info.outputPath("screenshots/floating-answered-reopened.png") });
  await page.getByRole("button", { name: "Tanya tentang kode" }).click();
  await page.getByRole("textbox", { name: "Pertanyaan", exact: true }).fill("Mengapa dikalikan?");
  await page.screenshot({ path: info.outputPath("screenshots/floating-follow-up.png") });
  await toggle.click();
  await toggle.click();
  await expect(page.getByRole("textbox", { name: "Pertanyaan", exact: true })).toHaveValue("Mengapa dikalikan?");
  await editor.fill("print('milik saya')");
  const secondResponse = page.waitForResponse("**/api/zyra/chat");
  await page.getByRole("button", { name: "Buat kode" }).click();
  await secondResponse;
  await expect(page.getByRole("button", { name: "Gunakan kode di editor" })).toBeVisible();
  await expect(editor).toContainText("print('milik saya')");
  await page.getByRole("button", { name: "Gunakan kode di editor" }).click();
  await expect(editor).toContainText("print(24)");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  expect(errors).toEqual([]);
});
