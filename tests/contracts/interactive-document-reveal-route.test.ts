import { expect, mock, test } from "bun:test";
import { mintInteractiveDocumentGrant } from "@/lib/materials/interactive-document-grant";
import { createHash } from "node:crypto";
import sharp from "sharp";
import { zipSync } from "fflate";

process.env.BETTER_AUTH_SECRET = "test-only-secret";
mock.module("server-only", () => ({}));
mock.module("@/lib/storage", () => ({ storage: {} }));
const { buildLocalVerificationFixture } = await import("../../scripts/authoring/local-verification-fixture");
const { validateProductBundleAdmission } = await import("@/lib/bundle/product-admission");
const { computeProductBundleChecksum, deterministicProductSerialization } = await import("@/lib/bundle/product-validator");
const sha = (bytes: Uint8Array) => createHash("sha256").update(bytes).digest("hex");
const html = Buffer.from("<!doctype html><p>Jawaban</p>");
const png = await sharp({ create: { width: 2, height: 2, channels: 4, background: "white" } }).png().toBuffer();
const spec = { id: "visual", kind: "interactive_document", version: 1, label: "Visual", description: "Visual interaktif", documentSha256: sha(html), documentBytes: html.length, printSha256: sha(png), printBytes: png.length, height: 400, staticFallback: { type: "text", summary: "Ringkasan", content: "Isi" }, printCaption: "Awal" };
const text = `\`\`\`zyx-visual\n${JSON.stringify(spec)}\n\`\`\``;
const fixture = buildLocalVerificationFixture().bundle;
const products = structuredClone(fixture.products);
const product = products.find(item => item.productType === "article");
if (!product || product.productType !== "article") throw new Error("ARTICLE_FIXTURE_MISSING");
const section = product.sections.find(item => item.blocks.some(block => block.formativeCheckPayload));
const block = section?.blocks.find(item => item.formativeCheckPayload);
if (!section || !block?.formativeCheckPayload) throw new Error("FORMATIVE_FIXTURE_MISSING");
block.formativeCheckPayload.explanation = text;
const formativeCheck = block.formativeCheckPayload;
const files = new Map(fixture.files);
const encode = (value: unknown) => new TextEncoder().encode(deterministicProductSerialization(value));
files.set("products.json", encode(products));
files.set(`visuals/${spec.documentSha256}.html`, html);
files.set(`visuals/${spec.printSha256}.png`, png);
const entityFiles = fixture.manifest.entityFiles.map(file => ({ ...file, checksum: sha(files.get(file.path)!) }));
const base = { ...fixture.manifest, entityFiles, visualAssets: [{ path: `visuals/${spec.documentSha256}.html`, sha256: spec.documentSha256, bytes: html.length }, { path: `visuals/${spec.printSha256}.png`, sha256: spec.printSha256, bytes: png.length }], bundleChecksum: undefined };
files.set("manifest.json", encode({ ...base, bundleChecksum: computeProductBundleChecksum(base, files) }));
const admission = await validateProductBundleAdmission(zipSync(Object.fromEntries(files)));
if (!admission.success) throw new Error(`FIXTURE_NOT_ADMITTED:${JSON.stringify(admission.issues)}`);
const bundle = admission.data;
const checksum = bundle.checksum;
let currentChecksum = checksum;
let userId = "admin";
let reads = 0;
mock.module("next/headers", () => ({ headers: async () => new Headers() }));
mock.module("@/lib/auth", () => ({ auth: { api: { getSession: async () => ({ user: { id: userId, role: "admin" } }) } } }));
mock.module("@/db", () => ({ db: {} }));
mock.module("@/lib/course-utils", () => ({ isEnrolled: async () => true }));
mock.module("@/lib/articles/structured-repository", () => ({ fetchSharedCanonicalArticle: async () => null }));
mock.module("@/lib/materials/formative-check-server", () => ({ resolvePublishedFormativeCheck: async () => ({ ok: false }) }));
mock.module("@/lib/materials/formative-check-draft-server", () => ({ resolveDraftProductFormativeCheck: async () => ({ ok: true, context: { formativeCheck, article: { courseId: "course" } } }) }));
mock.module("@/lib/bundle/product-staging", () => ({ getProductBundleImport: async () => ({ status: "draft", checksum: currentChecksum }), parseStagedProductBundle: async () => bundle }));
mock.module("@/lib/bundle/product-bundle-v2", () => ({ productEntityHash: () => "hash" }));
mock.module("@/lib/materials/interactive-document-assets", () => ({ readInteractiveDocumentAsset: async () => { reads++; return new Uint8Array([1]); } }));
mock.module("@/lib/materials/interactive-document-verified", () => ({ verifyAdmittedInteractiveDocumentAsset: () => {}, interactiveDocumentResponse: (bytes: Uint8Array) => new Response(bytes as unknown as BodyInit) }));
const route = await import("@/app/api/materials/interactive-document/reveal/route");
const grant = mintInteractiveDocumentGrant({ userId: "admin", articleId: product.id, articleVersion: product.version, sectionId: section.id, blockId: block.id, field: "explanation", draftId: "draft", draftChecksum: checksum }, "test-only-secret");
const query = new URLSearchParams({ grant, visualId: "visual", hash: spec.documentSha256, kind: "document" });
const request = (params = query) => new Request(`http://localhost/api?${params}`);

test("revealed asset requires a valid grant, current draft and exact field", async () => {
  const missing = new URLSearchParams(query); missing.set("grant", "invalid");
  expect((await route.GET(request(missing))).status).toBe(404);
  userId = "other";
  expect((await route.GET(request())).status).toBe(404);
  userId = "admin";
  currentChecksum = "d".repeat(64);
  expect((await route.GET(request())).status).toBe(404);
  currentChecksum = checksum;
  const wrong = new URLSearchParams(query); wrong.set("hash", "e".repeat(64));
  expect((await route.GET(request(wrong))).status).toBe(404);
  expect(reads).toBe(0);
  expect((await route.GET(request())).status).toBe(200);
  expect(reads).toBe(1);
});
